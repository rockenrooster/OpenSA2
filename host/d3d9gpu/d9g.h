// ------------------------------------------------------------------ faults
// Named faults for the negative controls (tools/s5/compare_hosts.py --controls), read
// from SA2_D3D9GPU_FAULT ("a,b"). The active set is written into the device's report
// and printed on stderr; compare_hosts.py refuses any verdict made under one.
enum Fault : uint32_t {
    F_CLEAR_COLOUR = 1,       // Clear's colour XOR 0x00010101
    F_COUNT_DRAW = 2,         // the first skipped draw left uncounted
    F_SCENE_ANSWER = 4,       // BeginScene inside a scene answers D3D_OK
    F_PRESENT_SCRIBBLE = 8,   // after each Present the back buffer is filled non-black
    F_GEOMETRY_NOOP = 32,    // omit geometry for the completed-pixel control
    F_CLEAR_NOOP = 16,        // Clear clears nothing and answers as it would
    F_SURFACE_LOST = 64,      // the 2nd to 4th Present find the window's surface lost (d9g_gpu_sdl.cpp)
};
struct FaultSet {
    uint32_t bits = 0;
    uint32_t map_bits = 0;    // the state check's mapping faults (d9g_pipeline.h MapFault, "map-...")
    std::string names;        // as given, "" for none
    std::string error;        // an unknown name
};
FaultSet parse_faults(const char* s);

