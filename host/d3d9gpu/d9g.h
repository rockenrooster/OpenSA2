// d9g.h: the second host's Direct3D 9 device, R2a (private/generated/s5/r2a/PLAN.md):
// the COM objects host/player calls, on SDL_gpu; its shaders are translated at creation by DXVK's
// compiler (R1, d9g_shader.h), and nothing is drawn with them yet (R2-draws). Every draw is
// validated as DXVK 3.1.1 validates it, answered as DXVK answers it, and counted as
// skipped (by method and primitive type); nothing is drawn. Everything else the player
// sends a device (state, resources, locks, clears, render-target switches, readback,
// Present) is implemented to DXVK's rules, each cited at the DXVK source line.
//
// Single-threaded by contract (the player calls it from one thread). No C++ exception
// crosses a COM method. The x87 control word and MXCSR are recorded around every SDL
// call that could move them (the device's report, "fpu").
